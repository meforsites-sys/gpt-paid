# -*- coding: utf-8 -*-
"""
يبني بنك الأسئلة الجديد: كل سؤال له شرح عربي في سطر وشرح إنجليزي في سطر مستقل.
المصدر: ملف المحتوى الأول (نفس الأسئلة والخيارات والإجابات) مع إعادة صياغة الشروح.
"""
import io, os, re, sys

sys.stdout.reconfigure(encoding='utf-8')
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..'))
sys.path.insert(0, os.path.join(ROOT, 'app', 'content'))
from grammar_content import TOPICS
from quiz_expl import EXPL

PAREN_LATIN = re.compile(r"\(([^()]*[A-Za-z][^()]*)\)")
LATIN_RUN = re.compile(r"[A-Za-z][A-Za-z'’\-\.]*(?:[ \t]+[A-Za-z][A-Za-z'’\-\.]*)*")

# تحسينات يدوية للشرح: (رقم الموضوع، نص السؤال) -> (شرح عربي، شرح إنجليزي)
OVERRIDES = {}


def clean_ar(t):
    t = re.sub(r"\(\s*\)", "", t)
    t = t.replace("⇒", " ").replace("→", " ")
    t = re.sub(r"\s*=>\s*", " ", t)
    t = re.sub(r"^\s*[\+\-:،,؛;\.]+\s*", "", t)
    t = re.sub(r"[\s]*[\+\-:،,؛;]\s*$", "", t)
    t = re.sub(r"\s{2,}", " ", t).strip()
    t = re.sub(r"\(\s+", "(", t)
    t = re.sub(r"\s+\)", ")", t)
    if t and t[0] in ':،,-' :
        t = t[1:].strip()
    if t and t[-1] in ':،,;-':
        t = t[:-1].strip()
    if t and t[-1] not in '.؟!':
        t += '.'
    return t


def split_expl(why):
    """يفصل الشرح إلى (عربي، إنجليزي)."""
    en_bits = []
    rest = why

    def grab(m):
        inner = m.group(1).strip()
        en_bits.append(inner)
        return ' '

    rest = PAREN_LATIN.sub(grab, rest)

    def grab2(m):
        s = m.group(0).strip()
        en_bits.append(s)
        return ' '

    rest = LATIN_RUN.sub(grab2, rest)
    ar = clean_ar(rest)
    en = ' · '.join([b for b in en_bits if b]).strip()
    en = re.sub(r'\s+', ' ', en)
    return ar, en


def main():
    from quiz_expl import EXPL as _E
    total = sum(len(t.get('quiz', [])) for t in TOPICS)
    missing = []
    for t in TOPICS:
        for idx in range(len(t.get('quiz', []))):
            if (int(t['id']), idx) not in _E:
                missing.append((int(t['id']), idx))
    if missing:
        print('MISSING EXPLANATIONS:', missing)
    else:
        print('all %d explanations provided' % total)
    out = {}
    for t in TOPICS:
        tid = int(t['id'])
        items = []
        for idx, q in enumerate(t.get('quiz', [])):
            qq, opts, ans, why = q
            ar, en = EXPL.get((tid, idx), split_expl(why))
            items.append((qq, list(opts), ans, ar, en))
        out[tid] = items

    # طباعة للمراجعة
    for tid in sorted(out):
        print('\n===== TOPIC %d =====' % tid)
        for q, opts, ans, ar, en in out[tid]:
            print('Q: %s' % q)
            print('   AR: %s' % ar)
            print('   EN: %s' % en)

    # كتابة الملف
    path = os.path.join(ROOT, 'app', 'content', 'quiz_bank.py')
    with io.open(path, 'w', encoding='utf-8') as f:
        f.write('# -*- coding: utf-8 -*-\n')
        f.write('# -*- auto-generated by build_quiz_bank.py -*-\n')
        f.write('QUIZ = {\n')
        for tid in sorted(out):
            f.write('  %d: [\n' % tid)
            for q, opts, ans, ar, en in out[tid]:
                f.write('    (%r,\n     %r,\n     %d,\n     %r,\n     %r),\n'
                        % (q, opts, ans, ar, en))
            f.write('  ],\n')
        f.write('}\n')
    print('\nwritten:', path)


if __name__ == '__main__':
    main()
